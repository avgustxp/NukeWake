using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Shared._Nuclear14.FactionReinforcement;
using Content.Shared.Roles;
using Content.Shared.StatusIcon;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using static Robust.Client.UserInterface.Controls.BoxContainer;

namespace Content.Client._Nuclear14.FactionReinforcement.UI;

[GenerateTypedNameReferences]
public sealed partial class FactionReinforcementWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _proto = default!;
    [Dependency] private IEntityManager _entity = default!;

    public event Action<string>? ReinforceRequested;

    public FactionReinforcementWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public void UpdateState(FactionReinforcementBoundUserInterfaceState state)
    {
        var spriteSystem = _entity.EntitySysManager.GetEntitySystem<SpriteSystem>();
        JobsContainer.Children.Clear();

        foreach (var entry in state.Jobs)
        {
            if (!_proto.TryIndex<JobPrototype>(entry.Job, out var job))
                continue;

            var button = new Button
            {
                HorizontalExpand = true,
                Disabled = entry.Status != FactionReinforcementStatus.Available,
                ToolTip = Loc.GetString(StatusLocKey(entry.Status)),
            };

            var row = new BoxContainer
            {
                Orientation = LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                Margin = new Thickness(4),
            };

            if (_proto.TryIndex<JobIconPrototype>(job.Icon, out var jobIcon))
            {
                row.AddChild(new TextureRect
                {
                    Texture = spriteSystem.Frame0(jobIcon.Icon),
                    MinSize = new Vector2(32, 32),
                    Stretch = TextureRect.StretchMode.KeepAspectCentered,
                });
            }

            var text = new BoxContainer
            {
                Orientation = LayoutOrientation.Vertical,
                HorizontalExpand = true,
                Margin = new Thickness(8, 0, 0, 0),
            };

            text.AddChild(new Label { Text = job.LocalizedName });
            text.AddChild(new Label
            {
                Text = Loc.GetString(StatusLocKey(entry.Status)),
                StyleClasses = { "LabelSubText" },
            });

            row.AddChild(text);
            button.AddChild(row);
            button.OnPressed += _ => ReinforceRequested?.Invoke(entry.Job);
            JobsContainer.AddChild(button);
        }
    }

    private static string StatusLocKey(FactionReinforcementStatus status)
    {
        // Never expose the exact reason why a role cannot be reinforced, otherwise
        // players can deliberately abuse the checks to deny the enemy faction a slot.
        return status == FactionReinforcementStatus.Available
            ? "faction-reinforcement-status-available"
            : "faction-reinforcement-status-unavailable";
    }
}
